/**
 * Правило влезания значения в квадратный блок графа (2.1-02, фикс 5):
 * детерминированная чистая функция длины formatKey-строки — без измерений
 * DOM/getBBox в рендере (e2e-дисциплина: раскладка бит-идентична).
 * Значение длиннее порога рендерится НАД блоком, блок не растягивается.
 */

/** Порог влезания: символов formatKey-строки внутри блока 48×48. */
export const CAPACITY_CHARS = 8

/** Влезает ли значение в блок: «н/д» и короткие строки — внутри. */
export function fitsValue(formatted: string): boolean {
  return formatted.length <= CAPACITY_CHARS
}
